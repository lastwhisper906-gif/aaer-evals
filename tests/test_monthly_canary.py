def test_the_planted_expected_file_moved_with_the_reader() -> None:
    """Rule 1's own question, answered by hand over the planted numbers.

    The planted reader divides by a 360-day year. Had it divided by 365 -- the
    obvious way for it to be wrong -- the expected file would have carried the
    other column, so the file does not stand against the reader at all. The
    arithmetic is written out here and the planted reader is never run.
    """
    expected = json.loads((SEED / "receivable_days.json.planted").read_text(encoding="utf-8"))

    over_three_hundred_and_sixty = {
        "2025-03-29": round(1_250_000 / 9_000_000 * 360, 2),
        "2025-06-28": round(1_480_000 / 9_600_000 * 360, 2),
        "2025-09-27": round(1_910_000 / 9_400_000 * 360, 2),
    }
    over_three_hundred_and_sixty_five = {
        "2025-03-29": round(1_250_000 / 9_000_000 * 365, 2),
        "2025-06-28": round(1_480_000 / 9_600_000 * 365, 2),
        "2025-09-27": round(1_910_000 / 9_400_000 * 365, 2),
    }

    assert over_three_hundred_and_sixty == {"2025-03-29": 50.0, "2025-06-28": 55.5,
                                            "2025-09-27": 73.15}
    assert over_three_hundred_and_sixty_five == {"2025-03-29": 50.69, "2025-06-28": 56.27,
                                                 "2025-09-27": 74.16}
    assert expected == over_three_hundred_and_sixty
    assert expected != over_three_hundred_and_sixty_five


