"""The monthly canary plants a known defect and records whether it was caught.

The judge is one dry run of `tools/monthly_canary.sh`, with its exit status read
directly rather than through a pipe. Every run here is the real routine: it
makes a git repository, puts a branch on it, plants the seed that ships in
`tools/seeded_defect`, and asks a `claude` shadowed on PATH. Only the lens is
stood in for, because the lens is the thing being measured and a real one would
answer differently every month.

Where the expected values come from
-----------------------------------

* **The plant.** `tools/seeded_defect/plant.json` says the defect is a rule-1
  violation and names the three paths it lands at. That file is written by hand
  and nothing generates it.
* **What the lens said.** Each stub answer below is written out here, the way
  `tests/test_second_lens.py` writes its verdicts. The routine's job is to sort
  those answers into hit and miss, and the sorting is what is asserted.
* **That the plant is a genuine defect.** Hand arithmetic, in
  `test_the_planted_expected_file_moved_with_the_reader`. The planted reader is
  never imported and never run here; the numbers are divided out in the test so
  a reader can follow them.
* **What may not be in the tree the lens reads.** Written out by hand in
  `test_the_manifest_keeps_every_file_that_gives_the_plant_away_out`, and not
  read back from the manifest the routine reads — a list that agrees with
  itself would let a file be dropped from both at once and stay green.

The fixture repository carries the seed, this file and the routine's document
on its `main`, because that is where they are once this branch merges and the
plant grows on a worktree off `main`. A fixture without them never runs the
step that takes them back out again.

Nothing here asserts what the routine returned. A stub says `fail` at rule 1 on
`tests/test_receivable_days.py`, and the run has to call that a hit because the
manifest planted that file under that rule — if the classifier were wrong in the
obvious way the expected value would not move with it.

The exit codes come from `src/canary.py`, which is where the script takes them
from as well, except `NO_LENS_RAN`, which is written out as `3` because the
shell has to know it before any Python has run and two copies of a number that
decides whether a month counts as verified is one copy too many.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

from src import canary

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "tools" / "monthly_canary.sh"
SEED = REPO_ROOT / "tools" / "seeded_defect"

PLANTED_TEST = "tests/test_receivable_days.py"
PLANTED_EXPECTED = "tests/fixtures/receivable_days.json"
PLANTED_READER = "src/receivable_days.py"


def verdict(*findings: dict, decision: str = "fail", reads: int = 11) -> str:
    return json.dumps(
        {
            "lens": "refute-check",
            "verdict": decision,
            "findings": list(findings),
            "reads": reads,
        }
    )


def finding(rule: int, file: str, reason: str = "the expected file came from a run") -> dict:
    return {"rule": rule, "file": file, "line": 7, "reason": reason}


NAMED_THE_PLANT = verdict(finding(1, PLANTED_TEST))
NAMED_THE_READER = verdict(finding(1, f"./{PLANTED_READER}"))
NAMED_SOMETHING_ELSE = verdict(finding(1, "src/market.py"))
RIGHT_FILE_WRONG_RULE = verdict(finding(3, PLANTED_TEST, "a date past the cutoff"))
NAMED_IT_AND_ASKED = verdict(finding(1, PLANTED_EXPECTED), decision="needs_judgment")
FOUND_NOTHING = verdict(decision="pass")

# A month already in the ledger, carrying the previous run's answer in it.
LAST_MONTH = json.dumps(
    {
        "routine": "seeded-defect-canary",
        "defect": "the expected file was regenerated by the reader it judges",
        "rule": 1,
        "result": "hit",
        "named": PLANTED_EXPECTED,
        "lens": "refute-check",
        "model": "claude-fable-5-1",
        "findings_count": 4,
        "planted_on": "0000000",
        "at": "2026-08-01T09:00:00+00:00",
    }
)


def claude_stub(directory: Path, *, exit_code: int, result: str | None) -> None:
    """A `claude -p --output-format json` that prints one envelope."""
    if result is None:
        envelope = ""
    else:
        envelope = json.dumps(
            {
                "type": "result",
                "is_error": False,
                "result": result,
                "modelUsage": {"claude-fable-5-1": {"inputTokens": 1}},
            }
        )
    stub = directory / "claude"
    stub.write_text(
        "#!/bin/sh\n"
        'pwd >> "$STUB_CWD"\n'
        f"printf %s {json.dumps(envelope)}\n"
        f"exit {exit_code}\n",
        encoding="utf-8",
    )
    stub.chmod(0o755)


def repository(tmp_path: Path) -> Path:
    """A git repository with one commit on `main` and nothing else in it.

    It carries this repository's own `.gitignore` and an interpreter directory
    for the routine to link, because both are what the tree the lens reads is
    actually made of: a scheduled task starts from a clone, the clone has an
    interpreter beside it, and the routine links that into the planted tree so
    the Stop hook has one. A fixture with neither never runs the branch that
    puts the symlink there, and that branch is how an untracked entry reaches
    the tree under review.
    """
    repo = tmp_path / "repo"
    (repo / "src").mkdir(parents=True)
    (repo / "src" / "market.py").write_text("# the tree the branch grows from\n", encoding="utf-8")
    # And the two tracked files that name this routine and are not kept out:
    # `docs/HOW_WE_WORK.md`, because the repository documents its own routines
    # and no plant can hide that, and the check the Stop hook runs inside the
    # planted tree. A fixture holding only what comes out is a judge of the
    # keep-out list; what a lens reads is the rest of the tree.
    for stays in ("docs/HOW_WE_WORK.md", "src/plain_name_check.py"):
        (repo / stays).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REPO_ROOT / stays, repo / stays)
    (repo / ".venv" / "bin").mkdir(parents=True)
    shutil.copyfile(REPO_ROOT / ".gitignore", repo / ".gitignore")
    # The answer key, on the base the plant grows from -- which is where it is
    # once this branch merges. A fixture repository without it never runs the
    # step that takes it back out, and the routine would be measured on a tree
    # no monthly run will ever see again.
    # Every kept-out path, taken from the manifest rather than listed again
    # here: a fixture that names its own set goes out of date the day the list
    # grows, and then the run it exercises is one no month will ever see.
    ledger = "events/ledger.jsonl"
    for carries_the_answer in canary.keep_out(canary.read_plant(SEED)):
        source = REPO_ROOT / carries_the_answer
        destination = repo / carries_the_answer
        destination.parent.mkdir(parents=True, exist_ok=True)
        if carries_the_answer == ledger:
            # Last month's row rather than this repository's ledger: it is the
            # routine's own output, naming the defect and the file it landed
            # on, and from the second scheduled run onward it is on `main` too.
            destination.write_text(LAST_MONTH + "\n", encoding="utf-8")
        elif source.is_dir():
            shutil.copytree(source, destination)
        else:
            shutil.copyfile(source, destination)
    for command in (
        ["git", "init", "-q", "-b", "main"],
        ["git", "config", "user.email", "canary@example.invalid"],
        ["git", "config", "user.name", "canary"],
        ["git", "add", "-A"],
        ["git", "commit", "-q", "-m", "the tree the branch grows from"],
    ):
        subprocess.run(command, cwd=repo, check=True, capture_output=True)
    return repo


def run_canary(
    tmp_path: Path,
    *,
    result: str | None,
    exit_code: int = 0,
    keep: bool = False,
) -> subprocess.CompletedProcess:
    """One dry run of the routine, against a ledger this test owns."""
    stubs = tmp_path / "stubs"
    stubs.mkdir(exist_ok=True)
    claude_stub(stubs, exit_code=exit_code, result=result)
    repo = tmp_path / "repo"
    if not repo.exists():
        repository(tmp_path)
    environment = dict(os.environ)
    environment["PATH"] = f"{stubs}:{environment['PATH']}"
    environment["STUB_CWD"] = str(tmp_path / "cwd")
    environment["CANARY_REPO"] = str(repo)
    environment["CANARY_SEED"] = str(SEED)
    environment["CANARY_LEDGER"] = str(tmp_path / "ledger.jsonl")
    environment["CANARY_PYTHON"] = sys.executable
    environment["CANARY_DIR"] = str(tmp_path / "canary")
    # Where the routine would put it by default is outside the checkout, which
    # `test_the_tree_stands_outside_the_checkout_it_came_from` is what checks;
    # here it is named so the tests below can read it.
    environment["CANARY_WORKTREE"] = str(tmp_path / "tree")
    environment["CANARY_TIMEOUT"] = "60"
    if keep:
        environment["CANARY_KEEP"] = "yes"
    return subprocess.run(
        ["bash", str(SCRIPT)],
        capture_output=True,
        text=True,
        env=environment,
        cwd=tmp_path,
    )


def ledger_lines(tmp_path: Path) -> list[dict]:
    ledger = tmp_path / "ledger.jsonl"
    if not ledger.exists():
        return []
    return [json.loads(line) for line in ledger.read_text(encoding="utf-8").splitlines() if line]


PLANTED_BRANCH = "item/receivable-days"


def branches(tmp_path: Path) -> list[str]:
    listed = subprocess.run(
        ["git", "branch", "--format=%(refname:short)"],
        cwd=tmp_path / "repo",
        capture_output=True,
        text=True,
        check=True,
    )
    return [name for name in listed.stdout.split() if name != "main"]


