def test_the_planted_tree_carries_no_marker_saying_it_is_planted(tmp_path: Path) -> None:
    """A defect that announces itself measures the announcement."""
    run_canary(tmp_path, result=FOUND_NOTHING, keep=True)

    tree = tmp_path / "tree"
    for landed in (PLANTED_READER, PLANTED_TEST, PLANTED_EXPECTED):
        text = (tree / landed).read_text(encoding="utf-8")
        assert "planted" not in text.lower()
        assert "canary" not in text.lower()
    subject = subprocess.run(
        ["git", "log", "-1", "--format=%s"],
        cwd=tree,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.lower()
    assert "planted" not in subject and "canary" not in subject
    # The branch and the directory are in front of the lens too: the prompt
    # names the worktree's path and `git status` names the branch. Only the
    # names the routine chose are read -- the directory above them belongs to
    # whoever ran it.
    (branch,) = branches(tmp_path)
    for name in (branch.lower(), tree.name.lower()):
        assert "planted" not in name and "canary" not in name and "defect" not in name


