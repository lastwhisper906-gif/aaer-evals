def test_every_tracked_file_that_says_what_the_plant_is_is_kept_out() -> None:
    """The list against the repository, rather than against itself.

    A hand-written list goes stale the moment somebody writes the plant's
    description into a file nobody thought of — a routine document, a changelog
    line, a second test. This asks `git grep` for the defect sentence over every
    file git tracks and requires each file holding it to be under a kept-out
    path. It is the check that survives the next person.

    Every tracked file, with nothing exempted. `archive/` was skipped here once
    — four thousand files, present in full in the planted tree, holding neither
    string today and read by nothing tomorrow. A judge with a directory it does
    not look in has a directory the leak can move to.
    """
    plant = canary.read_plant(SEED)
    kept_out = canary.keep_out(plant)

    # Three strings out of the manifest, each a different way to give the plant
    # away: what is wrong with it, the branch it arrives on, and the title it is
    # presented under -- which is the one rule 2 of tools/lens_prompt.md sends
    # the lens to look up in the task list.
    for giveaway in (plant["defect"], plant["branch"], plant["item"]):
        found = subprocess.run(
            ["git", "grep", "-I", "-l", "-F", "--", giveaway],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
        )
        assert found.returncode in (0, 1), found.stderr
        says_it = found.stdout.split()

        assert says_it, f"{giveaway!r} is nowhere, so the manifest is not in use"
        for name in says_it:
            assert any(
                name == out or name.startswith(f"{out}/") for out in kept_out
            ), f"{name} carries {giveaway!r} and is not kept out of the tree the lens reads"


